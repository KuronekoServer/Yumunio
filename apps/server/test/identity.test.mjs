import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { getMigrations } from 'better-auth/db/migration';
import { createIdentity } from '@yumunio/identity';
import { createAppServer } from '../server.mjs';
import { SqliteSnapshotStore } from '../snapshot-store.mjs';
import { createDemoWorkspace } from '../../web/public/store.js';

test('Node HTTP preserves separate account cookies and never treats an account session as snapshot access', async t => {
  const store = new SqliteSnapshotStore(':memory:');
  const mail = []; let identity;
  const server = createAppServer({ snapshotStore: store, accessKey: 'snapshot-fixture-key-'.repeat(3), identity: { handle: (...args) => identity.handle(...args) } });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const origin = 'http://127.0.0.1:' + server.address().port;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await identity?.flushBackgroundTasks(); store.close(); });
  identity = createIdentity({ database: store.database, origin, secret: 'account-fixture-key-'.repeat(3), registrationMode: 'open', sendMail: async message => { mail.push(message); return { status: 'accepted' }; } });
  await (await getMigrations(identity.auth.options)).runMigrations();
  await store.write(0, createDemoWorkspace());
  const post = (path, body, cookie) => fetch(origin + path, { method: 'POST', redirect: 'manual', headers: { Origin: origin, 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: JSON.stringify(body) });
  const email = 'http-fixture@example.invalid', password = 'http-long-fixture-password';
  assert.equal((await post('/api/auth/sign-up/email', { name: 'HTTP Fixture', email, password })).status, 202);
  await identity.flushBackgroundTasks();
  const token = new URL(mail[0].text.split('\n').at(-1)).searchParams.get('verify');
  assert.equal((await fetch(origin + '/api/auth/verify-email?token=' + encodeURIComponent(token) + '&callbackURL=' + encodeURIComponent(origin + '/account.html'), { redirect: 'manual' })).status, 200);
  const login = await post('/api/auth/sign-in/email', { email, password, rememberMe: false });
  assert.equal(login.status, 200);
  const loginBody = await login.json();
  assert.equal(loginBody.authenticated, true);
  assert.equal(Object.hasOwn(loginBody, 'token'), false);
  const cookies = login.headers.getSetCookie();
  assert.equal(cookies.length, 2);
  assert.ok(cookies.every(cookie => /HttpOnly/i.test(cookie)));
  const cookie = cookies.map(value => value.split(';')[0]).join('; ');
  const session = await (await fetch(origin + '/api/auth/get-session', { headers: { Cookie: cookie } })).json();
  assert.equal(session.user.email, email);
  assert.equal(Object.hasOwn(session.session, 'token'), false);
  assert.equal(Object.hasOwn(session.session, 'ipAddress'), false);
  assert.equal((await fetch(origin + '/api/workspace/snapshot', { headers: { Cookie: cookie } })).status, 401);
  const logout = await post('/api/auth/sign-out', {}, cookie);
  assert.equal(logout.status, 200);
  assert.ok(logout.headers.getSetCookie().length >= 2);
  assert.equal(await (await fetch(origin + '/api/auth/get-session', { headers: { Cookie: cookie } })).json(), null);
  assert.equal((await store.read()).revision, 1);
});
